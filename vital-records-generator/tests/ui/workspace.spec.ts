import { test, expect } from '@playwright/test'
const sample = 'ssn,owner,rescode,address,city,dob,dod,sex,age\n123456789,JANE DOE,001,10 MAIN ST,NEW ORLEANS,01021940,03042020,F,080\n987654321,JOHN DOE,002,20 OAK ST,BATON ROUGE,01011980,03042020,M,040'
test('imports, edits, filters, adds rows, exports, and persists preferences', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror',error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Vital Records Generator'})).toBeVisible()
  await page.locator('input[type=file]').setInputFiles({name:'sample.csv',mimeType:'text/csv',buffer:Buffer.from(sample)})
  await expect(page.getByRole('cell',{name:'Jane Doe',exact:true})).toBeVisible()
  await expect(page.getByRole('cell',{name:'***-**-6789',exact:true})).toBeVisible()
  await page.getByRole('cell',{name:'Jane Doe',exact:true}).dblclick()
  await page.getByRole('textbox',{name:'Edit Owner',exact:true}).fill('JANE SMITH')
  await page.getByRole('textbox',{name:'Edit Owner',exact:true}).press('Enter')
  await expect(page.getByRole('cell',{name:'Jane Smith',exact:true})).toBeVisible()
  await page.getByRole('textbox',{name:'Search records'}).fill('Smith')
  await expect(page.getByRole('cell',{name:'John Doe',exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Filters',exact:true}).click()
  await page.getByLabel('Filter age',{exact:true}).selectOption('65+')
  await page.getByRole('button',{name:'Export',exact:true}).click()
  await page.getByLabel('Export format').selectOption('json')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button',{name:'Save report'}).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('vital-records.json')
  await page.getByRole('button',{name:'Add row',exact:true}).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Owner',{exact:true}).fill('NEW RECORD')
  await dialog.getByRole('button',{name:'Add record',exact:true}).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button',{name:'Validation issues',exact:true}).click()
  await expect(page.getByText('Manual entry · line 0')).toBeVisible()
  await page.getByRole('button',{name:'Theme: light',exact:true}).click()
  await expect(page.locator('.workspace')).toHaveAttribute('data-theme','dark')
  await page.reload()
  await expect(page.locator('.workspace')).toHaveAttribute('data-theme','dark')
  expect(errors).toEqual([])
})
